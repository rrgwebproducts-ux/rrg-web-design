#!/usr/bin/env node
// 2026-11-18 (Brenton): PLP region content → static HTML (spec.md §32).
//
// The Bike Racks and Roof Boxes PLPs carry per-region buying advice (Shop By advice panel), a
// below-grid buying guide (How to choose, table, Fitting & roof bars, FAQs) and the hero
// paragraph. Tim wants all of it indexable, so it has to be in the page's HTML on first load —
// not fetched or injected by JS. The copy lives in content/{au,nz,uk}/{category}.json; this
// script writes it into marked blocks in each page:
//
//   <!-- plp-content:hero:start … -->   … <!-- plp-content:hero:end -->
//   <!-- plp-content:advice:start … --> … <!-- plp-content:advice:end -->
//   <!-- plp-content:guide:start … -->  … <!-- plp-content:guide:end -->
//
// Every region's copy is written (tagged .plp-rgn[data-region]); plp.css shows only the active
// region's. Production (Magento) renders only its own store's copy.
//
// Run from the repo root after editing any content/*.json file:
//   node tools/build-plp-content.mjs          (writes the pages)
//   node tools/build-plp-content.mjs --check  (exits 1 if a page is out of date; writes nothing)
//
// JSON inline markup: **bold**, [link text](todo:what the link needs) → a TODO placeholder link,
// href="#" plus a "TODO placeholder link — …" comment (each JSON file lists its own in _todo). A bullet starting "! " is a watch-out (! icon), otherwise ✓.
// A body array item that is itself an array becomes a <ul>.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGIONS = ['au', 'nz', 'uk'];
const PAGES = [
  { page: 'prototypes/plp/index.html', category: 'bike-racks' },
  { page: 'prototypes/plp-roof-boxes/index.html', category: 'roof-boxes' }
];
const GENERATED = (category, block) =>
  `generated by tools/build-plp-content.mjs from content/{au,nz,uk}/${category}.json (${block}) — edit the JSON and re-run, do not edit this block by hand`;

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
function inline(s) {
  return esc(s)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\(todo:([^)]+)\)/g, (_, text, what) => `<a href="#" data-todo-link="${what}">${text}</a><!-- TODO placeholder link — ${what} -->`);
}
const plain = s => String(s).replace(/\*\*(.+?)\*\*/g, '$1').replace(/\[([^\]]+)\]\(todo:[^)]+\)/g, '$1');

function body(items, indent) {
  return (items || []).map(item => Array.isArray(item)
    ? `${indent}<ul>\n${item.map(li => `${indent}  <li>${inline(li)}</li>`).join('\n')}\n${indent}</ul>`
    : `${indent}<p>${inline(item)}</p>`).join('\n');
}

function load(category) {
  const out = {};
  for (const r of REGIONS) out[r] = JSON.parse(readFileSync(join(ROOT, 'content', r, `${category}.json`), 'utf8'));
  return out;
}

const placeholderNote = (c, r) => c[r].placeholder ? `<!-- PLACEHOLDER copy (${r.toUpperCase()}) — current live category wording, to be expanded later -->` : '';

function heroHTML(c) {
  return REGIONS.map(r => {
    const todo = c[r].hero.todo ? `<!-- ${esc(c[r].hero.todo)} -->` : '';
    return `<span class="plp-rgn" data-region="${r}">${inline(c[r].hero.description)}</span>${todo}`;
  }).join('');
}

function adviceHTML(c) {
  // Tab order: AU's, then any tab only another region has.
  const keys = [];
  REGIONS.forEach(r => c[r].advice.forEach(a => { if (!keys.includes(a.tab)) keys.push(a.tab); }));
  const panels = keys.map(key => {
    const variants = REGIONS.map(r => {
      const a = c[r].advice.find(x => x.tab === key);
      if (!a) return '';
      const id = `plpAdviceTitle-${key}-${r}`;
      const bodyId = `plpAdviceBody-${key}-${r}`;
      const lis = a.bullets.map(b => b.startsWith('! ')
        ? `            <li class="is-warn">${inline(b.slice(2))}</li>`
        : `            <li class="is-tick">${inline(b)}</li>`).join('\n');
      // Accordion (2026-11-18, Brenton: the open panel pushed the products below the fold). The title is
      // the toggle; the body is closed by default but always in the HTML (indexed). plp.js opens/closes
      // every panel together, so switching tabs keeps the shopper's choice.
      return `      <div class="plp-rgn" data-region="${r}" role="region" aria-labelledby="${id}">
        <h3 class="plp-advice-title" id="${id}"><button type="button" class="plp-advice-toggle" aria-expanded="false" aria-controls="${bodyId}">${inline(a.title)}</button></h3>
        <div class="plp-advice-body" id="${bodyId}">
          <p class="plp-advice-intro">${inline(a.intro)}</p>
          <ul class="plp-advice-list">
${lis}
          </ul>${a.footer ? `\n          <p class="plp-advice-foot">${inline(a.footer)}</p>` : ''}
        </div>
      </div>`;
    }).filter(Boolean).join('\n');
    return `    <div class="plp-advice" id="plpAdvice-${key}" data-advice-tab="${key}"${key === 'all' ? '' : ' hidden'}>
${variants}
    </div>`;
  }).join('\n');
  return `  <div class="plp-advice-wrap" id="plpAdvice" aria-live="polite">
${panels}
  </div>`;
}

function tableHTML(t, indent) {
  const head = `${indent}<thead><tr>${t.head.map(h => `<th scope="col">${inline(h)}</th>`).join('')}</tr></thead>`;
  const rows = t.rows.map(row => `${indent}  <tr>${row.map((cell, i) => i === 0 && t.rowHeaders
    ? `<th scope="row">${inline(cell)}</th>` : `<td>${inline(cell)}</td>`).join('')}</tr>`).join('\n');
  return `${indent.slice(2)}<div class="plp-guide-table-wrap">
${indent}<table class="plp-guide-table">
${head}
${indent}<tbody>
${rows}
${indent}</tbody>
${indent}</table>
${indent.slice(2)}</div>${t.note ? `\n${indent.slice(2)}<p class="plp-guide-note">${inline(t.note)}</p>` : ''}`;
}

function guideHTML(c) {
  const section = (id, render) => {
    const variants = REGIONS.map(r => {
      const note = placeholderNote(c, r);
      return `    <div class="plp-rgn" data-region="${r}">${note ? '\n      ' + note : ''}
${render(c[r].guide, r)}
    </div>`;
    }).join('\n');
    return `  <section class="plp-guide-section" id="${id}">
${variants}
  </section>`;
  };
  const how = section('plpHowToChoose', g => `      <h2>${inline(g.howToChoose.heading)}</h2>\n${body(g.howToChoose.body, '      ')}`);
  const table = section('plpGuideTable', g => `      <h2>${inline(g.table.heading)}</h2>\n${tableHTML(g.table, '        ')}`);
  const fitting = section('plpFitting', g => `      <h2>${inline(g.fitting.heading)}</h2>\n${body(g.fitting.body, '      ')}`);
  // FAQs: native <details>, first one open, every answer in the HTML.
  const faqs = section('plpFaqs', g => `      <h2>${inline(g.faqs.heading)}</h2>
      <div class="faq-list">
${g.faqs.items.map((f, i) => `        <details class="faq-item"${i === 0 ? ' open' : ''}>
          <summary>${inline(f.q)}</summary>
          <div class="faq-answer">${(Array.isArray(f.a) ? f.a : [f.a]).map(p => `<p>${inline(p)}</p>`).join('')}</div>
        </details>`).join('\n')}
      </div>`);
  // FAQPage structured data, one per region (production outputs only its own store's).
  const ld = REGIONS.map(r => {
    const data = {
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: c[r].guide.faqs.items.map(f => ({
        '@type': 'Question',
        name: plain(f.q),
        acceptedAnswer: { '@type': 'Answer', text: (Array.isArray(f.a) ? f.a : [f.a]).map(plain).join(' ') }
      }))
    };
    return `  <script type="application/ld+json" data-region="${r}">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;
  }).join('\n');
  return `<section class="plp-guide" id="plpGuide" aria-label="Buying guide">
${how}
${table}
${fitting}
${faqs}
${ld}
</section>`;
}

// Line endings: a page edited on Windows can end up with CRLF. Generated blocks follow the page's
// own line ending, and --check ignores CRLF/LF differences (git normalises them on commit anyway).
function replaceBlock(html, name, category, content, page, eol) {
  const re = new RegExp(`(<!-- plp-content:${name}:start[^>]*-->)([\\s\\S]*?)(<!-- plp-content:${name}:end -->)`);
  if (!re.test(html)) throw new Error(`${page}: missing <!-- plp-content:${name}:start --> … <!-- plp-content:${name}:end --> markers`);
  const start = `<!-- plp-content:${name}:start — ${GENERATED(category, name)} -->`;
  const inner = (name === 'hero' ? content : `\n${content}\n`).replace(/\r?\n/g, eol);
  return html.replace(re, () => `${start}${inner}<!-- plp-content:${name}:end -->`);
}

const check = process.argv.includes('--check');
let stale = 0;
for (const { page, category } of PAGES) {
  const file = join(ROOT, page);
  const before = readFileSync(file, 'utf8');
  const c = load(category);
  const eol = before.includes('\r\n') ? '\r\n' : '\n';
  let html = before;
  html = replaceBlock(html, 'hero', category, heroHTML(c), page, eol);
  html = replaceBlock(html, 'advice', category, adviceHTML(c), page, eol);
  html = replaceBlock(html, 'guide', category, guideHTML(c), page, eol);
  const norm = t => t.replace(/\r\n/g, '\n');
  if (norm(html) === norm(before)) { console.log(`up to date  ${page}`); continue; }
  if (check) { console.log(`OUT OF DATE ${page}`); stale++; continue; }
  writeFileSync(file, html);
  console.log(`wrote       ${page}`);
}
if (stale) process.exit(1);
